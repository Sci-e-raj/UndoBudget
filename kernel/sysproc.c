uint64
sys_hello(void)
{
  int a, b, c, d;

  argint(0, &a);
  argint(1, &b);
  argint(2, &c);
  argint(3, &d);
  // Widen before adding; the user interface returns a signed 32-bit int.
  long sum = (long)a + b + c + d;
  if (sum < (-2147483647L - 1) || sum > 2147483647L)
    return -1;
  return sum;
}

